#!/usr/bin/env python3
"""Expand the FunctionalInequalities source tree and check local import paths.

This is a navigation/layout inventory, not a proof-status or axiom audit.
"""

from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
LIBRARY = Path("formalization/FunctionalInequalities")
OUTPUT = Path("formalization/MODULES.md")
IMPORT = re.compile(r"^import\s+(FunctionalInequalities(?:\.[A-Za-z0-9_]+)+)\s*$", re.M)


def inventory(root: Path) -> dict:
    paths = sorted((root / LIBRARY).rglob("*.lean"))
    rows = []
    for path in paths:
        relative = path.relative_to(root / LIBRARY).as_posix()
        source = path.read_text()
        title = re.search(r"/\-!\s*\n#\s+([^\n]+)", source)
        rows.append({"path": relative,
                     "module": "FunctionalInequalities." + relative[:-5].replace("/", "."),
                     "title": title[1].strip() if title else path.stem,
                     "imports": IMPORT.findall(source)})
    known = {row["module"] for row in rows}
    graph = {row["module"]: row["imports"] for row in rows}
    errors = []
    for row in rows:
        for module in row["imports"]:
            if module not in known:
                errors.append(f"{row['path']}: unresolved local import {module}")
        if (root / LIBRARY / row["path"]).with_suffix("").is_dir():
            errors.append(f"{row['path']}: file/directory family collision")
    visiting, visited = set(), set()

    def visit(module: str) -> None:
        if module in visiting:
            errors.append(f"Import cycle at {module}")
            return
        if module in visited or module not in graph:
            return
        visiting.add(module)
        for dependency in graph[module]:
            visit(dependency)
        visiting.remove(module)
        visited.add(module)

    for module in graph:
        visit(module)
    folded = Counter(row["path"].casefold() for row in rows)
    errors.extend(f"Case-insensitive filename collision: {p}" for p, count in folded.items() if count > 1)
    return {"modules": rows, "count": len(rows),
            "families": dict(sorted(Counter(row["path"].split("/")[0] for row in rows).items())),
            "local_import_edges": sum(len(v) for v in graph.values()), "errors": errors}


def tree_lines(paths: list[str]) -> list[str]:
    tree = {}
    for path in paths:
        node = tree
        for part in path.split("/"):
            node = node.setdefault(part, {})
    lines = ["FunctionalInequalities/"]

    def walk(node: dict, prefix: str) -> None:
        items = sorted(node.items(), key=lambda item: (not bool(item[1]), item[0]))
        for index, (name, children) in enumerate(items):
            last = index == len(items) - 1
            lines.append(prefix + ("└── " if last else "├── ") + name + ("/" if children else ""))
            if children:
                walk(children, prefix + ("    " if last else "│   "))

    walk(tree, "")
    return lines


def render(data: dict) -> str:
    out = ["# FunctionalInequalities module filenames", "",
           "Generated by `python3 research/module_inventory.py` from current source files.",
           "Check freshness with `python3 research/module_inventory.py --check`.",
           "This is a filename/import directory; it does not assign proof or paper-coverage status.", "",
           "[Source guide](README.md) · [Interface guide](../LEAN_DESIGN.md) · "
           "[Placement and naming](../research/naming.md) · "
           "[Filename review](../research/decisions/2026-10-17-functionalinequalities-filenames.md)", "",
           f"**{data['count']} Lean modules in {len(data['families'])} top-level families.** "
           "The library aggregate `FunctionalInequalities.lean` is outside this subtree.", "",
           "| Family | Modules |", "| --- | ---: |"]
    out.extend(f"| [{family}/](FunctionalInequalities/{family}) | {count} |"
               for family, count in data["families"].items())
    out.extend(["", "## Complete expanded tree", "", "```text",
                *tree_lines([row["path"] for row in data["modules"]]), "```", "",
                "## File links and source titles", "",
                "Titles below are copied from source module documentation, not independently reviewed claims.",
                "Use a file's import path by replacing `/` with `.` and dropping `.lean`, after the prefix "
                "`FunctionalInequalities.`."])
    for family in data["families"]:
        out.extend(["", f"### {family}", "", "| File | Source title |", "| --- | --- |"])
        for row in data["modules"]:
            if row["path"].split("/")[0] != family:
                continue
            title = row["title"].replace("|", "&#124;")
            out.append(f"| [{row['path']}](FunctionalInequalities/{row['path']}) | {title} |")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated navigation without writing it")
    parser.add_argument("--json", type=Path, help="write a detailed inventory to this explicit path")
    args = parser.parse_args()
    data = inventory(ROOT)
    if data["errors"]:
        print("\n".join(data["errors"]))
        return 1
    text = render(data)
    if args.check:
        if not (ROOT / OUTPUT).is_file() or (ROOT / OUTPUT).read_text() != text:
            print(f"Stale module directory: {OUTPUT}")
            return 1
    else:
        (ROOT / OUTPUT).write_text(text)
    if args.json:
        args.json.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(f"Module directory: {data['count']} modules, {data['local_import_edges']} local import edges, no layout errors.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
