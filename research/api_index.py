#!/usr/bin/env python3
"""Generate a source-bound, compiler-derived public API directory and offline search page."""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import html
import json
import os
import shlex
from pathlib import Path
import subprocess
import sys

import module_inventory

ROOT = Path(__file__).resolve().parents[1]
DRIVER = 'research/APIIndex.lean'
ENTRY = 'formalization/API.md'
FORMAT = 1


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_inputs(root: Path) -> dict[str, str]:
    names = [str(p.relative_to(root)) for p in sorted((root / module_inventory.LIBRARY).rglob('*.lean'))]
    names += ['formalization/FunctionalInequalities.lean', 'formalization/lakefile.toml',
              'formalization/lake-manifest.json', 'formalization/lean-toolchain', DRIVER,
              'research/api_index.py', 'research/module_inventory.py']
    return {p: sha(root / p) for p in sorted(names)}


def digest(inputs: dict[str, str]) -> str:
    return hashlib.sha256(json.dumps(inputs, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def validate_payload(payload: dict, root: Path, inventory: dict) -> list[dict]:
    owners = {r['module']: 'formalization/FunctionalInequalities/' + r['path'] for r in inventory['modules']}
    owners['FunctionalInequalities'] = 'formalization/FunctionalInequalities.lean'
    if set(payload['modules']) != set(owners) or len(payload['modules']) != len(owners):
        raise ValueError('Compiler import coverage differs from the current source module inventory')
    seen, rows = set(), []
    lengths = {m: len((root / p).read_text().splitlines()) for m, p in owners.items()}
    for original in payload['declarations']:
        row = dict(original)
        name, owner = row['name'], row['module']
        if owner not in owners or name in seen:
            raise ValueError('Unknown declaration owner or duplicate public name: ' + name)
        if name.startswith('_private.') or any(p.startswith('_') for p in name.split('.')):
            raise ValueError('Private/internal name in public API data: ' + name)
        if not isinstance(row['type'], str) or not row['type'].strip():
            raise ValueError('Missing compiler type: ' + name)
        if not isinstance(row['universes'], list) or not all(isinstance(x, str) for x in row['universes']):
            raise ValueError('Invalid universe parameters: ' + name)
        if row['kind'] not in {'axiom', 'definition', 'theorem', 'opaque', 'quotient', 'inductive', 'constructor', 'recursor'}:
            raise ValueError('Unknown declaration kind: ' + name)
        start, end = row['source_line'], row['source_end_line']
        if (start is None) != (end is None) or (start is not None and (
                not isinstance(start, int) or not isinstance(end, int)
                or not 1 <= start <= end <= lengths[owner])):
            raise ValueError('Compiler source range is outside its current source: ' + name)
        if row['docstring'] is not None and not isinstance(row['docstring'], str):
            raise ValueError('Invalid docstring: ' + name)
        seen.add(name)
        row.update(source_path=owners[owner], family=owner.split('.')[1] if '.' in owner else 'Root')
        rows.append(row)
    if not rows:
        raise ValueError('Compiler exported no public declarations')
    return sorted(rows, key=lambda r: (r['module'], r['name']))



def observation_source(root: Path, inventory: dict) -> str:
    imports = sorted({'Lean', 'FunctionalInequalities'} | {r['module'] for r in inventory['modules']})
    body = (root / DRIVER).read_text().removeprefix('import Lean\n').lstrip('\n')
    return '\n'.join('import ' + m for m in imports) + '\n\n' + body

def render_entry(rows: list[dict], inventory: dict, input_digest: str, output_dir: str = 'build/api-index') -> str:
    suffix = '' if output_dir == 'build/api-index' else ' --output ' + shlex.quote(output_dir)
    counts = Counter(r['family'] for r in rows)
    kinds = Counter(r['kind'] for r in rows)
    lines = ['# Public API directory', '',
             f'Generated by `python3 research/api_index.py{suffix}`; check freshness with `python3 research/api_index.py --check{suffix}`.',
             'Compiler types, universe parameters, defining modules, source positions and source docstrings are available in the offline search page.',
             'This index records interfaces; it assigns no proof, paper-coverage or certificate status.', '',
             '[Library design](../LEAN_DESIGN.md) · [Calling examples](../examples/README.md) · [Module directory](MODULES.md) · [Review checklist](../research/workflow.md#review-after-mechanical-checks)', '',
             f'**{len(rows):,} public compiler declarations across {inventory["count"]} source modules and the aggregate root.**', '',
             '| Mathematical family | Public declarations | Modules |', '| --- | ---: | ---: |']
    for family, count in sorted(inventory['families'].items()):
        lines.append(f'| [{family}](FunctionalInequalities/{family}/) | {counts[family]:,} | {count} |')
    if counts['Root']:
        lines.append(f'| Aggregate root | {counts["Root"]:,} | 1 |')
    lines += ['', '## Search the complete interface', '',
              'From the repository root, generate and validate the index:', '', '```bash',
              'python3 research/api_index.py' + suffix, 'python3 research/api_index.py --check' + suffix, '```', '',
              f'Open `{output_dir}/index.html` locally. Search by declaration, module, type or docstring; combine keywords in any order and filter by family.',
              'Expand a result to copy its defining import and read the full type, source location and docstring.',
              f'The complete data is `{output_dir}/public-api.json`; `manifest.json` binds it to source hashes, the toolchain and generator.',
              'These large, reproducible outputs stay under ignored `build/`; this navigation page stays small.', '',
              'Generation builds the current library before extraction. The compiler import set must match every current library module.',
              'Private and internal names are filtered; public compiler-generated support may remain. A missing docstring or source range is reported explicitly.',
              'Displayed types use Lean notation with full names and universe information; the source and compiler remain authoritative.',
              'Pinned compiled Mathlib dependencies are trusted. The index performs no axiom audit or kernel replay and does not renew any verification receipt.', '',
              'Kinds: ' + ', '.join(f'{k}: {v:,}' for k, v in sorted(kinds.items())) + '.', '',
              f'Source/tool input digest: `{input_digest}`.', '']
    return '\n'.join(lines)


