def output_path(root: Path, argument: str) -> Path:
    path = (root / argument).resolve()
    if not path.is_relative_to((root / 'build').resolve()) or path == (root / 'build').resolve():
        raise ValueError('Generated search outputs must be in a dedicated directory under build/')
    return path


def check(root: Path, output: Path) -> dict:
    manifest = json.loads((output / 'manifest.json').read_text())
    inputs = source_inputs(root)
    if manifest['format'] != FORMAT or manifest['inputs'] != inputs or manifest['input_digest'] != digest(inputs):
        previous = manifest.get('inputs', {})
        changed = sorted(name for name in set(previous) | set(inputs) if previous.get(name) != inputs.get(name))
        detail = (f'{len(changed)} changed input' + ('s' if len(changed) != 1 else '') + '; '
                  + ', '.join(changed[:3])) if changed else 'format or input digest changed'
        raise ValueError(f'API index inputs are stale ({detail}); run python3 research/api_index.py')
    if set(manifest['outputs']) != {'index.html', 'public-api.json', 'compiler.json', 'Observe.lean'}:
        raise ValueError('Incomplete API output manifest')
    for name, checksum in manifest['outputs'].items():
        if name not in {'index.html', 'public-api.json', 'compiler.json', 'Observe.lean'} or sha(output / name) != checksum:
            raise ValueError('Generated API output changed: ' + name)
    payload = json.loads((output / 'compiler.json').read_text())
    inventory = module_inventory.inventory(root)
    if inventory['errors']:
        raise ValueError('Module inventory is invalid')
    if (output / 'Observe.lean').read_text() != observation_source(root, inventory):
        raise ValueError('Compiler observation imports differ from the current module inventory')
    rows = validate_payload(payload, root, inventory)
    expected = {'source_modules': inventory['count'], 'imported_modules': sorted(payload['modules']),
                'public_declarations': len(rows), 'with_source_ranges': sum(r['source_line'] is not None for r in rows),
                'with_docstrings': sum(r['docstring'] is not None for r in rows),
                'toolchain': (root / 'formalization/lean-toolchain').read_text().strip()}
    if any(manifest.get(k) != v for k, v in expected.items()):
        raise ValueError('API manifest summary differs from current compiler observations')
    if json.loads((output / 'public-api.json').read_text()) != rows:
        raise ValueError('Public API data differs from compiler observations')
    if (root / ENTRY).read_text() != render_entry(rows, inventory, digest(inputs), output.relative_to(root).as_posix()):
        raise ValueError('Generated API navigation is stale')
    if (output / 'index.html').read_text() != render_html(rows, digest(inputs), os.path.relpath(root, output).replace(os.sep, '/') + '/'):
        raise ValueError('Generated search page differs from the current renderer')
    return manifest


def generate(root: Path, output: Path) -> dict:
    output.mkdir(parents=True, exist_ok=True)
    inputs = source_inputs(root)
    inventory = module_inventory.inventory(root)
    if inventory['errors']:
        raise ValueError('Module inventory is invalid')
    (output / 'Observe.lean').write_text(observation_source(root, inventory))
    env = {**os.environ, 'GIT_OPTIONAL_LOCKS': '0', 'LEAN_NUM_THREADS': '2',
           'KLS_API_INDEX_OUTPUT': str(output / 'compiler.json')}
    for name in ['GIT_INDEX_FILE', 'GIT_DIR', 'GIT_WORK_TREE', 'LEAN_PATH', 'LEAN_SRC_PATH']:
        env.pop(name, None)
    for label, command in [('build', ['lake', 'build', 'FunctionalInequalities', *[r['module'] for r in inventory['modules']]]),
                           ('extract', ['lake', 'env', 'lean', '-DwarningAsError=true', str(output / 'Observe.lean')])]:
        with (output / (label + '.log')).open('w') as log:
            result = subprocess.run(command, cwd=root / 'formalization', env=env, stdout=log, stderr=subprocess.STDOUT)
        if result.returncode:
            raise ValueError(f'{label} failed; see {output / (label + ".log")}')
    if source_inputs(root) != inputs:
        raise ValueError('Source/tool inputs changed during compiler extraction; regenerate')
    inventory = module_inventory.inventory(root)
    if inventory['errors']:
        raise ValueError('Module inventory is invalid')
    payload = json.loads((output / 'compiler.json').read_text())
    rows = validate_payload(payload, root, inventory)
    (output / 'public-api.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2) + '\n')
    (output / 'index.html').write_text(render_html(rows, digest(inputs), os.path.relpath(root, output).replace(os.sep, '/') + '/'))
    (root / ENTRY).write_text(render_entry(rows, inventory, digest(inputs), output.relative_to(root).as_posix()))
    head = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, env=env, text=True).strip()
    manifest = {'format': FORMAT, 'input_digest': digest(inputs), 'inputs': inputs,
                'source_head': head, 'source_binding': 'current worktree source hashes, including uncommitted comments',
                'toolchain': (root / 'formalization/lean-toolchain').read_text().strip(),
                'source_modules': inventory['count'], 'imported_modules': sorted(payload['modules']),
                'public_declarations': len(rows), 'with_source_ranges': sum(r['source_line'] is not None for r in rows),
                'with_docstrings': sum(r['docstring'] is not None for r in rows),
                'outputs': {p: sha(output / p) for p in ['compiler.json', 'public-api.json', 'index.html', 'Observe.lean']},
                'trust_scope': 'Current library built by pinned Lean; pinned compiled Mathlib imports trusted. Interface observations only; no proof, axiom or certificate status inferred.'}
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return check(root, output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check existing source-bound outputs without rebuilding')
    parser.add_argument('--output', default='build/api-index')
    args = parser.parse_args()
    try:
        output = output_path(ROOT, args.output)
        result = check(ROOT, output) if args.check else generate(ROOT, output)
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    print(f'API index {"fresh" if args.check else "generated"}: {result["public_declarations"]} public declarations, '
          f'{result["source_modules"]} modules; {output / "index.html"}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
